""""Quick Heads Up" briefs, persisted per view; scheduled pushes live in reports.py.

One brief per view key: "default" (the public ranking) and "user:<id>" (that
user's personal ranking). Stored in ``HeadsUpBrief`` so the morning brief
survives server restarts. By default (``HEADS_UP_TTL_MINUTES=0``), briefs are
generated by the scheduled morning report or on demand via ``request_refresh``
(the Regenerate button), never automatically on every page load.
"""
from __future__ import annotations

import datetime as dt
import logging
import threading
import time
from typing import Any

from . import config, db, diversity, ollama, scoring

log = logging.getLogger("news.heads-up")

DEFAULT = "default"


def user_key(user_id: int) -> str:
    return f"user:{int(user_id)}"

_cache: dict[str, dict[str, Any]] = {}  # key -> {"text", "ts"}
_cache_lock = threading.Lock()
# /api/heads-up is public: one generation at a time, one queued per key, a pause after failures.
_gen_lock = threading.Lock()
_pending: set[str] = set()
_FAILURE_BACKOFF_SECONDS = 60
_last_failure: dict[str, float] = {}


def _load_db_entry(key: str) -> dict[str, Any] | None:
    try:
        with db.get_conn() as conn:
            row = conn.execute(
                "SELECT text, generated_at FROM HeadsUpBrief WHERE key = ?", (key,)
            ).fetchone()
    except Exception:  # noqa: BLE001
        return None
    if not row:
        return None
    parsed = db.parse_ts(row["generated_at"])
    ts = parsed.replace(tzinfo=dt.UTC).timestamp() if parsed else time.time()
    return {"text": str(row["text"]), "ts": ts}


def _save_db_entry(key: str, text: str, ts: float) -> None:
    stamp = dt.datetime.fromtimestamp(ts, dt.UTC).strftime("%Y-%m-%d %H:%M:%S")
    try:
        with db.get_conn() as conn:
            conn.execute(
                "INSERT INTO HeadsUpBrief (key, text, generated_at) VALUES (?, ?, ?) "
                "ON CONFLICT (key) DO UPDATE SET text = excluded.text, generated_at = excluded.generated_at",
                (key, text, stamp),
            )
    except Exception:  # noqa: BLE001
        log.warning("could not persist heads-up brief for %s", key)


def _get_entry(key: str) -> dict[str, Any] | None:
    with _cache_lock:
        entry = _cache.get(key)
    if entry is not None:
        return entry
    entry = _load_db_entry(key)
    if entry is not None:
        with _cache_lock:
            _cache.setdefault(key, entry)
            return _cache[key]
    return None


def _fresh(key: str, now: float) -> bool:
    entry = _cache.get(key)
    if entry is None:
        return False
    if config.HEADS_UP_TTL_MINUTES <= 0:
        return True
    return now - entry["ts"] < config.HEADS_UP_TTL_MINUTES * 60


def brief(force: bool = False, key: str = DEFAULT, *, max_stories: int = 5) -> tuple[str | None, bool]:
    """Return ``(text, cached)``, generating synchronously when forced or stale."""
    now = time.time()
    _get_entry(key)
    with _cache_lock:
        if not force and _fresh(key, now):
            return str(_cache[key]["text"]), True
        if not force and now - _last_failure.get(key, 0.0) < _FAILURE_BACKOFF_SECONDS:
            return _text(key), True
    if not _gen_lock.acquire(blocking=force):
        return last_brief(key), True
    try:
        return _generate(key, now, max_stories=max_stories)
    finally:
        _gen_lock.release()


def _format_status(entry: dict[str, Any] | None, generating: bool, now: float) -> dict[str, Any]:
    raw_age_h = max(0.0, (now - entry["ts"]) / 3600.0) if entry else None
    stale_after = config.HEADS_UP_STALE_HOURS
    stale = bool(entry and stale_after > 0 and raw_age_h is not None and raw_age_h >= stale_after)
    return {
        "text": entry["text"] if entry else None,
        "generating": generating,
        "generated_at": (dt.datetime.fromtimestamp(entry["ts"], dt.UTC).strftime("%Y-%m-%d %H:%M:%S")
                         if entry else None),
        "age_hours": round(raw_age_h, 2) if raw_age_h is not None else None,
        "stale": stale,
    }


def status(key: str = DEFAULT) -> dict[str, Any]:
    """The view's current brief. Auto-refreshes only when ``HEADS_UP_TTL_MINUTES > 0``."""
    now = time.time()
    entry = _get_entry(key)
    auto_ttl = config.HEADS_UP_TTL_MINUTES > 0
    with _cache_lock:
        entry = _cache.get(key) or entry
        start = (
            auto_ttl
            and not _fresh(key, now)
            and key not in _pending
            and now - _last_failure.get(key, 0.0) >= _FAILURE_BACKOFF_SECONDS
        )
        if start:
            _pending.add(key)
        generating = key in _pending
    if start:
        threading.Thread(target=_background, args=(key, False), name=f"heads-up-{key}", daemon=True).start()
    return _format_status(entry, generating, now)


def request_refresh(key: str = DEFAULT) -> dict[str, Any]:
    """Explicitly trigger one background brief regeneration (Regenerate button)."""
    now = time.time()
    entry = _get_entry(key)
    with _cache_lock:
        _last_failure.pop(key, None)
        start = key not in _pending
        if start:
            _pending.add(key)
        generating = key in _pending
    if start:
        threading.Thread(target=_background, args=(key, True), name=f"heads-up-{key}", daemon=True).start()
    return _format_status(entry, generating, now)


def invalidate(key: str) -> None:
    """Drop a cached brief (in memory and DB)."""
    with _cache_lock:
        _cache.pop(key, None)
        _last_failure.pop(key, None)
    try:
        with db.get_conn() as conn:
            conn.execute("DELETE FROM HeadsUpBrief WHERE key = ?", (key,))
    except Exception:  # noqa: BLE001
        pass


def _background(key: str, force: bool = False) -> None:
    try:
        with _gen_lock:
            if force or not _fresh(key, time.time()):
                _generate(key, time.time())
    finally:
        with _cache_lock:
            _pending.discard(key)


def _generate(key: str, now: float, *, max_stories: int = 5) -> tuple[str | None, bool]:
    user_id = int(key.removeprefix("user:")) if key != DEFAULT else None
    story_cap = max(3, min(30, int(max_stories or 5)))
    with db.get_conn() as conn:
        ranked = scoring.ranked_stories(conn, personal=user_id is not None, user_id=user_id, diverse=False)
        # Never treat satire/parody stories (e.g. Der Postillon) as real news in briefs.
        ranked = [i for i in ranked if not db.json_dict(i["story"]["metrics"]).get("satire")]
        # Personal brief: unread, or updated with significant news since it was read.
        if user_id is not None:
            ranked = [i for i in ranked if i["read"] != "read"]
        top = diversity.rerank(conn, ranked)[:story_cap]
        about = scoring.about_user(scoring.get_user_profile(conn, user_id)) if user_id else ""
    if not top:
        return None, False
    lines = []
    for item in top:
        s = item["story"]
        m = db.json_dict(s["metrics"])
        lines.append(f"- {s['headline']} | urgency={m.get('urgency_level')} "
                     f"status={m.get('status')} | {s['summary']}")
    system = "Write a concise 2-3 sentence news brief in plain text. Be factual, no preamble."
    if about:
        system += (" Write it for this reader, who describes themselves as follows (use it only to choose "
                   "emphasis and say briefly why an item matters to them, never as a source of facts):\n"
                   + about)
    try:
        text = ollama.strip_thinking(ollama.chat(
            [
                {"role": "system", "content": system},
                {"role": "user", "content": "Summarize these top stories for a reader:\n" + "\n".join(lines)},
            ],
            temperature=0.2,
            role="brief",
        ))
    except Exception as e:  # noqa: BLE001
        log.warning("heads-up generation (%s) failed: %s", key, e)
        with _cache_lock:
            _last_failure[key] = time.time()
        return None, False
    with _cache_lock:
        _cache[key] = {"text": text, "ts": now}
    _save_db_entry(key, text, now)
    return text, False


def _text(key: str) -> str | None:
    entry = _cache.get(key)
    return str(entry["text"]) if entry else None


def last_brief(key: str = DEFAULT) -> str | None:
    entry = _get_entry(key)
    return str(entry["text"]) if entry else None
