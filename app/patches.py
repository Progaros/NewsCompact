def _patch_tag_alias_review_2026_11_23(conn: sqlite3.Connection) -> str:
    approved = 0
    rejected = 0
    for alias, canonical in _TAG_REVIEW_2026_11_23_APPROVE:
        approved += conn.execute(
            "UPDATE TagAlias SET status = 'approved' WHERE alias = ? AND canonical = ? AND status = 'pending'",
            (alias, canonical),
        ).rowcount
    for alias, canonical in _TAG_REVIEW_2026_11_23_REJECT:
        rejected += conn.execute(
            "UPDATE TagAlias SET status = 'rejected' WHERE alias = ? AND canonical = ? AND status = 'pending'",
            (alias, canonical),
        ).rowcount
    return f"approved={approved}, rejected={rejected}"


_PATCHES: list[tuple[str, Callable[[sqlite3.Connection], str]]] = [
    ("2026-11-23-tag-alias-review", _patch_tag_alias_review_2026_11_23),
]


def apply_pending(conn: sqlite3.Connection) -> list[str]:
    """Run any unapplied patches in order and record them in ``DbPatch``."""
    applied = {r[0] for r in conn.execute("SELECT id FROM DbPatch").fetchall()}
    ran: list[str] = []
    for patch_id, fn in _PATCHES:
        if patch_id in applied:
            continue
        summary = fn(conn)
        conn.execute(
            "INSERT INTO DbPatch (id, summary) VALUES (?, ?)",
            (patch_id, summary),
        )
        ran.append(patch_id)
        log.info("applied DB patch %s (%s)", patch_id, summary)
    return ran
